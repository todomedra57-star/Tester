def poly(points):
    return "polygon(" + ", ".join(f"{x:.1f}% {y:.1f}%" for x, y in points) + ")"

def heart():
    pts = []
    for i in range(72):
        t = 2 * math.pi * i / 72
        x = 16 * math.sin(t) ** 3
        y = -(13 * math.cos(t) - 5 * math.cos(2 * t) - 2 * math.cos(3 * t) - math.cos(4 * t))
        pts.append((50 + x * 2.95, 46 + y * 2.95))
    return poly(pts)

def hexagon():
    return poly([(50 + 50 * math.cos(math.pi / 3 * i - math.pi / 2), 50 + 50 * math.sin(math.pi / 3 * i - math.pi / 2)) for i in range(6)])

