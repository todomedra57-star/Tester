def extend_variant(tokens, key, new_opts, fallback=None):
    tok = next((t for t in tokens if t["key"] == key), None)
    if tok is None:
        if fallback is None:
            return
        tok = fallback
        insert_at = next(i for i, t in enumerate(tokens) if t["type"] == "variant")
        tokens.insert(insert_at, tok)
    for k, ar, en in new_opts:
        if k not in tok["options"]:
            tok["options"].append(k)
            tok["choices"][k] = {"ar": ar, "en": en}

def variant_tok(key, opts):
    return {"key": key, "type": "variant", "options": [o[0] for o in opts], "choices": {o[0]: {"ar": o[1], "en": o[2]} for o in opts}}


