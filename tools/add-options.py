for name, c in T.items():
    d = ROOT / name
    man = json.loads((d / "manifest.json").read_text(encoding="utf-8"))
    toks = man["tokens"]
    extend_variant(toks, "photoFrame", NEW_FRAMES)
    extend_variant(toks, "galleryStyle", NEW_GALLERY, fallback=variant_tok("galleryStyle", [("strip", "شريط بسيط", "Simple strip")]))
    extend_variant(toks, "dateStyle", [o for o in NEW_DATES])
    extend_variant(toks, "ornament", ORNAMENT, fallback=variant_tok("ornament", ORNAMENT[:1]))
    if name == "midnight":
        extend_variant(toks, "countdownStyle", COUNTDOWN_NEW)
    if name in COVER_NEW:
        extend_variant(toks, "coverLayout", [COVER_NEW[name]])
    extend_variant(toks, "photoTone", [], fallback=variant_tok("photoTone", PHOTO_TONE))
    extend_variant(toks, "entrance", [], fallback=variant_tok("entrance", ENTRANCE))
    if LIVE[name]["foil"]:
        extend_variant(toks, "metal", [], fallback=variant_tok("metal", METAL))
    extend_variant(toks, "fontPair", [], fallback=variant_tok("fontPair", FONT_PAIR))
    names_have = {t["key"] for t in toks}
    first_var = next(i for i, t in enumerate(toks) if t["type"] == "variant")
    for fk, fv in FONT_TOKENS.items():
        if fk not in names_have:
            toks.insert(first_var, {"key": fk, "type": "font"}); first_var += 1
        man["defaultTheme"].setdefault(fk, fv)
    for k in ("galleryStyle", "ornament", "photoTone", "entrance", "metal", "fontPair"):
        if not any(t["key"] == k for t in toks):
            continue
        man["defaultTheme"].setdefault(k, next(t for t in toks if t["key"] == k)["options"][0])
    # calm defaults: gentle entrance, no ambient effect (couples can still choose them)
    man["defaultTheme"]["entrance"] = "gentle"
    man["defaultAnimation"]["ambient"] = "none"
    if "none" in man["couplePresets"].get("ambients", []):
        man["couplePresets"]["ambients"] = ["none"] + [a for a in man["couplePresets"]["ambients"] if a != "none"]
    vkeys = [v["key"] for v in man["couplePresets"]["variants"]]
    for t in toks:
        if t["type"] == "variant" and t["key"] not in vkeys:
            man["couplePresets"]["variants"].append({"key": t["key"]})
    have = {p["key"] for p in man["couplePresets"]["palettes"]}
    for key, ar, en, vals in PALETTES[name]:
        if key not in have:
            man["couplePresets"]["palettes"].append({"key": key, "name": {"ar": ar, "en": en}, "values": vals})
    (d / "manifest.json").write_text(json.dumps(man, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    css = (d / "style.css").read_text(encoding="utf-8")
    css = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", "", css, flags=re.S).rstrip() + "\n\n"
    (d / "style.css").write_text(css + css_pack(name, c), encoding="utf-8")

    # templates that print data-* only for the variants they already had
    html = (d / "template.html").read_text(encoding="utf-8")
    first_tag = html.split(">", 1)[0]
    attrs = [("data-gallery-style", "galleryStyle"), ("data-ornament", "ornament"), ("data-photo-tone", "photoTone"),
             ("data-entrance", "entrance"), ("data-font-pair", "fontPair")] + ([("data-metal", "metal")] if LIVE[name]["foil"] else [])
    for attr, key in attrs:
        if attr not in first_tag:
            html = html.replace(first_tag, first_tag + f' {attr}="{{{{variant "{key}"}}}}"', 1)
            first_tag = html.split(">", 1)[0]
    (d / "template.html").write_text(html, encoding="utf-8")
    opts = {t["key"]: len(t["options"]) for t in toks if t["type"] == "variant"}
    print(f"{name:13} palettes={len(man['couplePresets']['palettes'])} options={opts}")
